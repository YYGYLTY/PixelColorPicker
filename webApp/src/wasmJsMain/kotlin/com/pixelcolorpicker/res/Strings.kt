    /** 取字符串；找不到时返回 key 本身（与 Android 行为接近）。 */
    fun get(key: String, vararg args: Any?): String {
        val raw = when (current) {
            Lang.ZH -> ZH[key]
            Lang.EN -> EN[key]
            Lang.JA -> JA[key]
        } ?: ZH[key] ?: key
        if (args.isEmpty()) return raw
        // 支持 %1$s / %1$d / %s / %d 这类简单占位
        return format(raw, args)
    }

    private fun format(raw: String, args: Array<out Any?>): String {
        var out = raw
        args.forEachIndexed { i, a ->
            out = out.replace("%" + (i + 1) + "$s", a.toString())
            out = out.replace("%" + (i + 1) + "$d", a.toString())
            out = out.replace("%s", a.toString())
            out = out.replace("%d", a.toString())
        }
        return out
    }

